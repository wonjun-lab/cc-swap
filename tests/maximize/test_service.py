def test_detect_claude_path_order(tmp_path, monkeypatch):
    configured = _executable(tmp_path / "custom" / "claude")
    on_path = _executable(tmp_path / "brew" / "claude")
    local = _executable(tmp_path / "home" / ".local" / "bin" / "claude")
    monkeypatch.setattr(service.shutil, "which", lambda name: str(on_path))
    home = tmp_path / "home"
    assert service.detect_claude_path(str(configured), home=home) == str(configured)
    assert service.detect_claude_path(str(tmp_path / "gone"), home=home) == str(on_path)
    monkeypatch.setattr(service.shutil, "which", lambda name: None)
    assert service.detect_claude_path(None, home=home) == str(local)
    local.unlink()
    assert service.detect_claude_path(None, home=home) is None


def test_detect_claude_path_keeps_the_versioned_symlink_unresolved(tmp_path, monkeypatch):
    target = _executable(tmp_path / "versions" / "2.1.0")
    link = tmp_path / "home" / ".local" / "bin" / "claude"
    link.parent.mkdir(parents=True)
    link.symlink_to(target)
    monkeypatch.setattr(service.shutil, "which", lambda name: None)
    assert service.detect_claude_path(None, home=tmp_path / "home") == str(link)


