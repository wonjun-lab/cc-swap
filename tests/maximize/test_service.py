def test_uninstall_linux_disables_then_removes_the_unit(tmp_path, on_linux, fake_run):
    unit = service.unit_path(tmp_path)
    unit.parent.mkdir(parents=True)
    unit.write_text("x")
    run = fake_run({"systemctl is-active": [_done(0), _done(3)]})
