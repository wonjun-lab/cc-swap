def test_install_macos_writes_bootstraps_and_saves_claude_path(tmp_path, on_macos, fake_run, monkeypatch):
    claude = _executable(tmp_path / "brew" / "claude")
    monkeypatch.setattr(service.shutil, "which", lambda name: str(claude))
    root = tmp_path / "root"
    run = fake_run({"launchctl print": _done(1)})
    result = service.install(home=tmp_path, program=MAC_PROGRAM, uid=UID, backup_root=root)
    plist = Path(result["path"])
    assert plist == tmp_path / "Library" / "LaunchAgents" / "com.wonjun-lab.cc-swap.plist"
    assert plistlib.loads(plist.read_bytes())["ProgramArguments"] == [*MAC_PROGRAM, "auto"]
    assert (tmp_path / "Library" / "Logs" / "cc-swap").is_dir()
    assert ["launchctl", "bootstrap", f"gui/{UID}", str(plist)] in run.calls
    assert "bootout" not in [c[1] for c in run.calls]
    assert result["claude_path"] == str(claude) and result["claude_path_saved"] is True
    assert load_prime_settings(root).claude_path == str(claude)


