def _done(returncode: int = 0, stdout: str = "", stderr: str = ""):
    return subprocess.CompletedProcess(args=[], returncode=returncode, stdout=stdout, stderr=stderr)


class FakeRun:
    """subprocess.run stand-in: canned replies keyed "tool subcommand"; a
    list replays in order and then repeats its last item. Every argv is kept."""

    def __init__(self, replies: dict | None = None):
        self.replies = {
            k: list(v) if isinstance(v, list) else [v] for k, v in (replies or {}).items()
        }
        self.calls: list[list[str]] = []

    def __call__(self, argv, **kwargs):
        argv = list(argv)
        self.calls.append(argv)
        sub = argv[2] if argv[0] == "systemctl" else argv[1]
        queue = self.replies.get(f"{argv[0]} {sub}")
        if not queue:
            return _done(0)
        return queue.pop(0) if len(queue) > 1 else queue[0]


@pytest.fixture
def fake_run(monkeypatch):
    def install(replies=None):
        fake = FakeRun(replies)
        monkeypatch.setattr(subprocess, "run", fake)
        return fake

    return install


